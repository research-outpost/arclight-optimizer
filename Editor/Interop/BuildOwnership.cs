using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

namespace Okarin.AvatarTextureOptimizer.Editor
{
    // Which assets a pass may edit and save into. A build may only write what did not exist when it started: the
    // generated assets of NDMF, VRCFury, d4rk and any future tool, without naming their folders. The set is taken by
    // an SDK callback before every preprocess hook runs (VRCFury at -10000 is the earliest third-party one) and
    // mirrored to a file so a domain reload mid-build cannot lose it. Without a snapshot (tests, Play Mode before the
    // callback) the old conservative folder rule applies.
    internal static class BuildOwnership
    {
        private const string NdmfGenerated = "Packages/nadena.dev.ndmf/__Generated/";
        private static readonly string SnapshotFile = "Library/AvatarTextureOptimizer/ownership-snapshot.txt";

        private static HashSet<string> sourcePaths;
        private static bool snapshotChecked;

        // Called by the SDK hook before any other preprocess callback, and by Play Mode before its passes.
        internal static void Begin(GameObject avatar)
        {
            try
            {
                sourcePaths = new HashSet<string>(AssetDatabase.GetAllAssetPaths()
                    .Where(path => !path.StartsWith(NdmfGenerated, StringComparison.Ordinal) && !D4rkOrdering.IsD4rkOutputPath(path)),
                    StringComparer.Ordinal);
                snapshotChecked = true;
                Directory.CreateDirectory(Path.GetDirectoryName(SnapshotFile));
                File.WriteAllLines(SnapshotFile, sourcePaths);
            }
            catch (Exception e)
            {
                Debug.LogWarning("Arclight Optimizer: could not snapshot the project's assets; only known generated folders are writable. " + e.Message);
                sourcePaths = null;
                snapshotChecked = true;
            }
        }

        internal static bool IsBuildOwned(UnityEngine.Object asset)
        {
            if (!asset) return false;
            string path = AssetDatabase.GetAssetPath(asset);
            if (path.Length == 0) return true; // In memory: made during this build.
            if (LoadSnapshot()) return !sourcePaths.Contains(path);
            // No snapshot: only the containers known to be generated by a build are editable.
            return path.StartsWith(NdmfGenerated, StringComparison.Ordinal) || D4rkOrdering.IsD4rkOutput(asset);
        }

        // Tests and tooling can return to the folder rule without leaving a snapshot behind.
        internal static void Reset()
        {
            sourcePaths = null;
            snapshotChecked = false;
            try { if (File.Exists(SnapshotFile)) File.Delete(SnapshotFile); } catch (Exception) { }
        }

        private static bool LoadSnapshot()
        {
            if (snapshotChecked) return sourcePaths != null;
            snapshotChecked = true;
            try
            {
                if (!File.Exists(SnapshotFile)) return false;
                sourcePaths = new HashSet<string>(File.ReadAllLines(SnapshotFile), StringComparer.Ordinal);
                return true;
            }
            catch (Exception) { sourcePaths = null; return false; }
        }
    }
}
